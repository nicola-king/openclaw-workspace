PIPELINE_TEMPLATES = {
    "github-actions-ci": {
        "desc": "GitHub Actions CI — 构建+测试+Lint",
        "platform": "github",
    },
    "github-actions-cd": {
        "desc": "GitHub Actions CD — 自动部署",
        "platform": "github",
    },
    "azure-pipeline": {
        "desc": "Azure Pipeline — 全链路 IaC+App",
        "platform": "azure",
    },
    "gate-check": {
        "desc": "质量门禁 — 代码扫描+测试+安全",
        "platform": "generic",
    },
}

def generate_pipeline(pipeline_type: str = "github-actions-ci",
                      project_name: str = "taiyi-workspace",
                      targets: List[str] = None,
                      include_security: bool = True,
                      environments: List[str] = None) -> Dict:
    """
    生成 CI/CD 管道 YAML 配置

    参数:
      pipeline_type: github-actions-ci / github-actions-cd / azure-pipeline / gate-check
      project_name: 项目名
      targets: 目标 (如 ["skill-a", "skill-b"])
      include_security: 是否加入安全扫描
      environments: 环境列表 (如 ["dev", "staging", "prod"])

    返回:
      {status, yaml, type, platform, note}
    """
    envs = environments or ["dev"]
    tgts = targets or ["."]

    if pipeline_type == "github-actions-ci":
        yaml = _generate_github_ci(project_name, tgts, include_security)

    elif pipeline_type == "github-actions-cd":
        yaml = _generate_github_cd(project_name, envs, include_security)

    elif pipeline_type == "azure-pipeline":
        yaml = _generate_azure_pipeline(project_name, envs, include_security)

    elif pipeline_type == "gate-check":
        yaml = _generate_gate_check(project_name, tgts)

    else:
        return {"status": "error", "error": f"Unknown type: {pipeline_type}"}

    return {
        "status": "ok",
        "yaml": yaml,
        "type": pipeline_type,
        "platform": PIPELINE_TEMPLATES.get(pipeline_type, {}).get("platform", "?"),
        "note": f"Generated for {project_name}",
        "environments": envs,
    }

def _generate_github_ci(name: str, targets: List[str], security: bool) -> str:
    """生成 GitHub Actions CI pipeline"""
    lines = [
        f"# {name} — CI Pipeline",
        f"# Generated by Taiyi DevOps Engine",
        f"# Reference: Microsoft Symphony + Azure/ResourceModules patterns",
        f"",
        f"name: CI",
        f"",
        f"on:",
        f"  push:",
        f"    branches: [main, develop]",
        f"  pull_request:",
        f"    branches: [main]",
        f"",
        f"jobs:",
        f"  lint:",
        f"    runs-on: ubuntu-latest",
        f"    steps:",
        f"      - uses: actions/checkout@v4",
        f"      - name: Lint check",
        f"        run: |",
        f"          echo '::notice::Linting {name}'",
        f"          # TODO: add your linter here",
        f"",
        f"  test:",
        f"    needs: lint",
        f"    runs-on: ubuntu-latest",
        f"    steps:",
        f"      - uses: actions/checkout@v4",
        f"      - name: Run tests",
        f"        run: |",
        f"          echo '::notice::Testing {name}'",
        f"          # TODO: add test runner",
        f"",
        f"  build:",
        f"    needs: test",
        f"    runs-on: ubuntu-latest",
        f"    steps:",
        f"      - uses: actions/checkout@v4",
        f"      - name: Build",
        f"        run: |",
        f"          echo '::notice::Building {name}'",
    ]

    if security:
        lines.extend([
            f"",
            f"  security:",
            f"    needs: build",
            f"    runs-on: ubuntu-latest",
            f"    steps:",
            f"      - uses: actions/checkout@v4",
            f"      - name: Security scan",
            f"        run: |",
            f"          echo '::notice::Security scan - {name}'",
            f"          # Reference: Microsoft REST API Fuzz Testing patterns",
            f"          pip install bandit 2>/dev/null",
            f"          bandit -r . -f json || true",
        ])

    return "\n".join(lines)

def _generate_github_cd(name: str, envs: List[str], security: bool) -> str:
    """生成 GitHub Actions CD pipeline — 参考 Symphony 多环境模式"""
    env_stages = []
    for i, env in enumerate(envs):
        env_stages.append(f"""
  deploy-{env}:
    needs: [lint, test, build{'security' if security else ''}]
    runs-on: ubuntu-latest
    environment: {env}
    steps:
      - uses: actions/checkout@v4
      - name: Deploy to {env}
        run: |
          echo '::notice::Deploying {name} to {env}'
          # Reference: Microsoft Symphony multi-orchestrator pattern
          # TODO: add deployment script
""")

    return f"""# {name} — CD Pipeline (Multi-Environment)
# Reference: Microsoft Symphony IaC CI/CD patterns
#
# Environments: {', '.join(envs)}
# Deployment model: Sequential promote (dev → staging → prod)

name: CD

on:
  push:
    tags:
      - 'v*'

jobs:
  lint:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Validate
        run: echo '::notice::Validating {name}'

  test:
    needs: lint
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Test
        run: echo '::notice::Testing {name}'

  build:
    needs: test
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Build
        run: echo '::notice::Building {name}'
{'  security:' if security else ''}
    {'needs: build' if security else ''}
    {'runs-on: ubuntu-latest' if security else ''}
    {'steps:' if security else ''}
      {'- name: Security scan' if security else ''}
        {'run: |' if security else ''}
          {'echo "Security scan - {name}"' if security else ''}
          {'pip install bandit 2>/dev/null; bandit -r . -f json || true' if security else ''}

{''.join(env_stages)}"""

def _generate_azure_pipeline(name: str, envs: List[str], security: bool) -> str:
    """生成 Azure Pipeline — 参考 Symphony + ResourceModules"""
    return f"""# {name} — Azure Pipeline
# Reference: Microsoft Symphony multi-orchestrator + Azure/ResourceModules CI platform
#
# Environments: {', '.join(envs)}

trigger:
  - main
  - develop

pool:
  vmImage: ubuntu-latest

variables:
  - group: {name}-vars

stages:
  - stage: Validate
    jobs:
      - job: Lint
        steps:
          - script: echo "Linting {name}"

      - job: Test
        steps:
          - script: echo "Testing {name}"

  - stage: Build
    jobs:
      - job: Build
        steps:
          - script: echo "Building {name}"

  - stage: Deploy
    jobs:
      - deployment: DeployToDev
        environment: dev
        strategy:
          runOnce:
            deploy:
              steps:
                - script: echo "Deploying to dev"
"""

def _generate_gate_check(name: str, targets: List[str]) -> str:
    """质量门禁 — 参考 MS REST API Fuzz Testing 安全理念"""
    return f"""# {name} — Quality Gate
# Reference: Microsoft REST API Fuzz Testing (RAFT) security patterns
#           + Azure/ResourceModules testing platform

name: Quality Gate

on:
  pull_request:
    branches: [main]

jobs:
  gate:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - name: Code Quality
        run: |
          echo '::notice::Code quality check'
          # Check for secrets
          git diff --cached --name-only || true

      - name: Security Gate
        run: |
          echo '::notice::Security scan'
          # Check for sensitive patterns
          echo "Gate: $(date)"
"""

