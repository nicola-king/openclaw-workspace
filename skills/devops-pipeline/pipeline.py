def status() -> Dict:
    """管道状态总报告"""
    health = check_health()
    gate = gate_check()
    return {
        "timestamp": datetime.now().isoformat(),
        "health": health,
        "gate": gate,
        "summary": f"🟢 Health: {health['summary']} | 🟢 Gate: {gate['summary']}",
    }

