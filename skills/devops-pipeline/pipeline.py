if __name__ == "__main__":
    import sys
    if len(sys.argv) < 2:
        print("🔧 太一 DevOps Pipeline 引擎")
        print()
        print("用法:")
        print("  pipeline generate <type> [name]    生成管道 YAML")
        print("  pipeline health                    健康检查")
        print("  pipeline gate [target]             质量门禁")
        print("  pipeline deploy [env] [--dry-run]  执行部署")
        print("  pipeline status                    状态报告")
        print("  pipeline module <type> <name>      模块化组件")
        print()
        print("管道类型: github-actions-ci / github-actions-cd / azure-pipeline / gate-check")
        print("模块类型: pipeline / security-scan / deployment")
        print("环境: dev / staging / prod")
        sys.exit(0)

    cmd = sys.argv[1]

    if cmd == "generate":
        ptype = sys.argv[2] if len(sys.argv) > 2 else "github-actions-ci"
        name = sys.argv[3] if len(sys.argv) > 3 else "taiyi-workspace"
        r = generate_pipeline(pipeline_type=ptype, project_name=name)
        print(r.get("yaml", ""))

    elif cmd == "health":
        r = check_health()
        for name, c in r.get("checks", {}).items():
            icon = "✅" if c["status"] == "ok" else ("⚠️" if c["status"] == "warn" else "❌")
            print(f"  {icon} {name}: {c.get('detail','')}")
        print(f"\n  {r['summary']}")

    elif cmd == "gate":
        target = sys.argv[2] if len(sys.argv) > 2 else "."
        r = gate_check(target)
        for c in r.get("checks", []):
            icon = "✅" if c["status"] == "ok" else ("⚠️" if c["status"] == "warn" else "❌")
            print(f"  {icon} {c['name']}: {c.get('detail','')}")
        print(f"\n  {r['summary']}")

    elif cmd == "deploy":
        env = sys.argv[2] if len(sys.argv) > 2 else "local"
        dry = "--exec" not in sys.argv
        r = deploy(environment=env, dry_run=dry)
        for s in r.get("steps", []):
            icon = "✅" if s["status"] == "ok" else ("⏳" if s["status"] == "simulated" else "❌")
            print(f"  {icon} {s['action']}: {s['status']}")
        print(f"  ({r.get('note','')})")

    elif cmd == "status":
        r = status()
        print(r["summary"])

    elif cmd == "module":
        mtype = sys.argv[2] if len(sys.argv) > 2 else "pipeline"
        name = sys.argv[3] if len(sys.argv) > 3 else "custom"
        r = module(mtype, name)
        if r["status"] == "ok":
            print(r.get("yaml", ""))
        else:
            print(f"❌ {r.get('error','')}")
            print(f"   可用: {', '.join(r.get('available',[]))}")

    else:
        print(f"未知命令: {cmd}")
