# 模块化管道模板（参考 Azure/ResourceModules）
# =====================================================================

def module(module_type: str = "pipeline", name: str = "custom-module") -> Dict:
    """生成模块化管道组件"""
    # Build YAML manually to avoid f-string/brace conflicts
    pipe_yaml = (
        "# Pipeline Module: " + name + "\n"
        "# Reference: Azure/ResourceModules modular CI platform\n"
        "parameters:\n"
        "  - name: environment\n"
        "    type: string\n"
        "    default: dev\n"
        "\n"
        "jobs:\n"
        "  - job: ${{{{ parameters.environment }}}}\n"
        "    steps:\n"
        "      - script: echo \"Module " + name + " running on ${{{{ parameters.environment }}}}}\"\n"
    )
    sec_yaml = (
        "# Security Scan Module: " + name + "\n"
        "# Reference: Microsoft REST API Fuzz Testing (RAFT)\n"
        "steps:\n"
        "  - script: |\n"
        "      echo \"Security scanning " + name + "\"\n"
        "      # Secret scanning\n"
        "      # Dependency scanning\n"
        "      # SAST scanning\n"
    )
    dep_yaml = (
        "# Deployment Module: " + name + "\n"
        "# Reference: Microsoft Symphony multi-environment pattern\n"
        "parameters:\n"
        "  - name: environment\n"
        "    type: string\n"
        "    \n"
        "steps:\n"
        "  - script: |\n"
        "      echo \"Deploying " + name + " to ${{{{ parameters.environment }}}}\"\n"
        "      # Immutable deployment\n"
        "      # Health check\n"
        "      # Rollback on failure\n"
    )

    modules = {
        "pipeline": pipe_yaml,
        "security-scan": sec_yaml,
        "deployment": dep_yaml,
    }

    if module_type not in modules:
        return {"status": "error", "error": f"Unknown module: {module_type}",
                "available": list(modules.keys())}

    return {"status": "ok", "module": module_type, "name": name,
            "yaml": modules[module_type]}

