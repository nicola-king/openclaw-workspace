def check_health() -> Dict:
    """检查管道基础设施健康"""
    t0 = time.time()
    checks = {}

    # Git 健康
    try:
        r = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                          capture_output=True, text=True, timeout=5,
                          cwd=str(WORKSPACE_DIR))
        checks["git"] = {"status": "ok", "detail": r.stdout.strip()[:8]}
    except: checks["git"] = {"status": "error"}

    # 定时任务（cron）
    try:
        r = subprocess.run(["crontab", "-l"], capture_output=True, text=True, timeout=5)
        cron_count = len([l for l in r.stdout.split("\n") if l.strip() and not l.startswith("#")])
        checks["cron"] = {"status": "ok", "detail": f"{cron_count} tasks"}
    except: checks["cron"] = {"status": "error"}

    # OpenClaw Gateway
    try:
        r = subprocess.run(["openclaw", "gateway", "status"],
                          capture_output=True, text=True, timeout=10)
        checks["gateway"] = {"status": "ok" if "running" in r.stdout.lower() else "warn",
                             "detail": r.stdout.split("\n")[0][:60] if r.stdout else "?"}
    except: checks["gateway"] = {"status": "error"}

    errors = sum(1 for c in checks.values() if c["status"] == "error")
    warns = sum(1 for c in checks.values() if c["status"] == "warn")

    return {
        "status": "error" if errors else ("warn" if warns else "ok"),
        "elapsed_ms": int((time.time() - t0) * 1000),
        "checks": checks,
        "summary": f"{len(checks)} services: {len(checks)-errors-warns} ok, {warns} warn, {errors} error",
    }

