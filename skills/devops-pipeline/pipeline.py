def deploy(environment: str = "local", target: str = "all",
           dry_run: bool = True) -> Dict:
    """执行发布部署"""
    t0 = time.time()

    if dry_run:
        return {
            "status": "dry-run",
            "environment": environment,
            "target": target,
            "elapsed_ms": int((time.time() - t0) * 1000),
            "steps": [
                {"step": 1, "action": f"Git commit + tag", "status": "simulated"},
                {"step": 2, "action": f"Push to origin/main", "status": "simulated"},
                {"step": 3, "action": f"CI pipeline trigger", "status": "simulated"},
                {"step": 4, "action": f"Deploy to {environment}", "status": "simulated"},
                {"step": 5, "action": "Health check post-deploy", "status": "simulated"},
            ],
            "note": "Dry run — set dry_run=False to execute",
        }

    # 真实部署
    steps = []
    # 1. Git commit + tag
    try:
        tag = f"deploy-{datetime.now().strftime('%Y%m%d-%H%M%S')}"
        subprocess.run(["git", "add", "-A"], cwd=str(WORKSPACE_DIR), capture_output=True, timeout=30)
        subprocess.run(["git", "commit", "-m", f"[deploy] {tag}"], cwd=str(WORKSPACE_DIR), capture_output=True, timeout=30)
        subprocess.run(["git", "tag", tag], cwd=str(WORKSPACE_DIR), capture_output=True, timeout=10)
        subprocess.run(["git", "push", "origin", "main", "--tags"], cwd=str(WORKSPACE_DIR), capture_output=True, timeout=60)
        steps.append({"step": 1, "action": f"Git tagged {tag}", "status": "ok"})
    except Exception as e:
        steps.append({"step": 1, "action": "Git deploy", "status": "error", "error": str(e)[:50]})

    elapsed = int((time.time() - t0) * 1000)
    return {"status": "ok" if all(s["status"] == "ok" for s in steps) else "partial",
            "environment": environment, "target": target,
            "elapsed_ms": elapsed, "steps": steps}

