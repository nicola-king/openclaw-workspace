def gate_check(target: str = ".") -> Dict:
    """本地质量门禁检查"""
    checks = []
    t0 = time.time()

    # 1. Git 状态
    try:
        r = subprocess.run(["git", "status", "--porcelain"],
                          capture_output=True, text=True, timeout=10,
                          cwd=str(WORKSPACE_DIR))
        modified = len([l for l in r.stdout.split("\n") if l.strip()])
        checks.append({"name": "git-status", "status": "ok" if modified < 50 else "warn",
                       "detail": f"{modified} files modified"})
    except: checks.append({"name": "git-status", "status": "error"})

    # 2. 磁盘使用率
    try:
        r = subprocess.run(["df", "-h", str(WORKSPACE_DIR)], capture_output=True, text=True, timeout=5)
        usage = r.stdout.split("\n")[1].split()[4] if len(r.stdout.split("\n")) > 1 else "?"
        checks.append({"name": "disk-usage", "status": "ok" if usage.endswith("%") and int(usage.rstrip("%")) < 85 else "warn",
                       "detail": usage})
    except: checks.append({"name": "disk-usage", "status": "error"})

    # 3. 内存
    try:
        r = subprocess.run(["free", "-h"], capture_output=True, text=True, timeout=5)
        mem_line = r.stdout.split("\n")[1].split()
        avail = float(mem_line[6].rstrip("Gi"))
        checks.append({"name": "memory", "status": "ok" if avail > 2 else "warn",
                       "detail": f"{avail}Gi available"})
    except: checks.append({"name": "memory", "status": "error"})

    # 4. 管道文件一致性
    pipeline_dir = SKILL_DIR / "pipelines"
    checks.append({"name": "pipeline-configs", "status": "ok",
                   "detail": "inline templates"})

    errors = [c for c in checks if c["status"] == "error"]
    warns = [c for c in checks if c["status"] == "warn"]

    return {
        "status": "error" if errors else ("warn" if warns else "ok"),
        "elapsed_ms": int((time.time() - t0) * 1000),
        "target": target,
        "checks": checks,
        "summary": f"{len(checks)} checks: {len(checks)-len(errors)-len(warns)} ok, {len(warns)} warn, {len(errors)} error",
    }

